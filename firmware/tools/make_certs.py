"""Regenerate include/certs.h: the root certificates the light trusts for https:// hubs.

Tailscale Funnel (and most hosts) use Let's Encrypt, which chains to ISRG Root X1 (RSA)
or X2 (ECDSA). Run from firmware/:  python3 tools/make_certs.py
Add more roots to ROOTS if your hub uses another certificate authority.
"""

from pathlib import Path

ROOTS = [Path("/etc/ssl/certs/ISRG_Root_X1.pem"), Path("/etc/ssl/certs/ISRG_Root_X2.pem")]

pem = "".join(p.read_text().strip() + "\n" for p in ROOTS)
lines = "\n".join(f'    "{line}\\n"' for line in pem.splitlines())
Path("include/certs.h").write_text(
    "#pragma once\n// Generated by tools/make_certs.py: ISRG Root X1 + X2 (Let's Encrypt).\n"
    f"static const char HUB_ROOT_CAS[] =\n{lines};\n"
)
print("wrote include/certs.h")
